ALTER TABLE employees
    ADD COLUMN profile_image_key TEXT,
    ADD COLUMN profile_image_mime VARCHAR(80),
    ADD CONSTRAINT employees_profile_image_key_format
        CHECK (
            (profile_image_key IS NULL AND profile_image_mime IS NULL)
            OR (
                profile_image_key ~ '^[a-f0-9]{64}$'
                AND profile_image_mime IN ('image/jpeg', 'image/png', 'image/webp')
            )
        );

CREATE UNIQUE INDEX employees_profile_image_key_unique
    ON employees (profile_image_key)
    WHERE profile_image_key IS NOT NULL;

ALTER TABLE learning_resources
    ADD COLUMN view_count BIGINT NOT NULL DEFAULT 0,
    ADD CONSTRAINT learning_resources_view_count_nonnegative CHECK (view_count >= 0);

CREATE INDEX learning_resources_popular_media_idx
    ON learning_resources (view_count DESC, published_at DESC)
    WHERE status = 'APPROVED' AND resource_type IN ('VIDEO', 'AUDIO');

CREATE TABLE lesson_youtube_recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL CHECK (length(btrim(title)) > 0),
    youtube_url TEXT NOT NULL CHECK (length(youtube_url) <= 2048),
    created_by BIGINT REFERENCES employees(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX lesson_youtube_recommendations_lesson_idx
    ON lesson_youtube_recommendations (lesson_id, created_at DESC, id DESC);
