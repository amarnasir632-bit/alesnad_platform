CREATE TABLE password_reset_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    email_key CHAR(64) NOT NULL CHECK (email_key ~ '^[a-f0-9]{64}$'),
    ip_key CHAR(64) NOT NULL CHECK (ip_key ~ '^[a-f0-9]{64}$'),
    token_hash CHAR(64) UNIQUE CHECK (token_hash IS NULL OR token_hash ~ '^[a-f0-9]{64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ,
    used_at TIMESTAMPTZ,
    CONSTRAINT password_reset_expiration_valid CHECK (expires_at IS NULL OR expires_at > created_at)
);

CREATE INDEX password_reset_request_email_window_idx
    ON password_reset_requests (email_key, created_at DESC);

CREATE INDEX password_reset_request_ip_window_idx
    ON password_reset_requests (ip_key, created_at DESC);

CREATE INDEX password_reset_request_created_at_idx
    ON password_reset_requests (created_at);

CREATE INDEX password_reset_token_lookup_idx
    ON password_reset_requests (token_hash, expires_at)
    WHERE token_hash IS NOT NULL AND used_at IS NULL;
