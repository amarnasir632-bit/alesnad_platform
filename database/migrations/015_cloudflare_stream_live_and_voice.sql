-- Add lesson reference to live sessions, video processing status to learning resources, and voice participation signaling.
ALTER TABLE live_sessions
    ADD COLUMN IF NOT EXISTS lesson_id BIGINT REFERENCES lessons(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS live_sessions_lesson_idx
    ON live_sessions (lesson_id)
    WHERE lesson_id IS NOT NULL;

ALTER TABLE learning_resources
    ADD COLUMN IF NOT EXISTS video_processing_status VARCHAR(30) DEFAULT 'ready';

CREATE TABLE IF NOT EXISTS session_voice_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES live_sessions(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'REVOKED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (session_id, student_id)
);

CREATE INDEX IF NOT EXISTS session_voice_requests_session_status_idx
    ON session_voice_requests (session_id, status);
