-- One-time, expiring invitations for staff accounts. Raw tokens are never stored.
CREATE TABLE staff_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT staff_invitation_expiration_check CHECK (expires_at > created_at),
    CONSTRAINT staff_invitation_final_state_check CHECK (accepted_at IS NULL OR revoked_at IS NULL)
);
CREATE INDEX staff_invitations_pending_idx ON staff_invitations (expires_at) WHERE accepted_at IS NULL AND revoked_at IS NULL;
CREATE UNIQUE INDEX staff_invitations_one_pending_per_user ON staff_invitations (user_id) WHERE accepted_at IS NULL AND revoked_at IS NULL;

