-- Manual platform-wide content access, independent of payment processing.
CREATE TABLE manual_content_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
    granted_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    grant_reason VARCHAR(500),
    revoked_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    revoked_at TIMESTAMPTZ,
    revocation_reason VARCHAR(500),
    CONSTRAINT manual_access_revocation_fields_check CHECK (revoked_at IS NOT NULL OR revoked_by IS NULL)
);

CREATE UNIQUE INDEX manual_content_access_one_active_per_student
    ON manual_content_access (student_id)
    WHERE revoked_at IS NULL;
CREATE INDEX manual_content_access_history_idx
    ON manual_content_access (student_id, granted_at DESC);

INSERT INTO permissions (code, display_name, description)
VALUES ('content_access.manage', 'منح وسحب وصول المحتوى', 'منح أو سحب أهلية الطالب للوصول إلى محتوى المنصة يدويًا.')
ON CONFLICT (code) DO NOTHING;

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
JOIN permissions p ON p.code = 'content_access.manage'
WHERE r.code IN ('content_reviewer', 'admin')
ON CONFLICT (role_id, permission_id) DO NOTHING;
