-- Initial PostgreSQL schema for the Academic Support Platform.
-- Apply through: php database/migrate.php

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(32),
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_full_name_not_blank CHECK (length(btrim(full_name)) > 0)
);

CREATE UNIQUE INDEX users_email_lower_unique ON users (lower(email));

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    display_name VARCHAR(100) NOT NULL,
    description TEXT,
    is_system_role BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(120) NOT NULL UNIQUE,
    display_name VARCHAR(150) NOT NULL,
    description TEXT
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    PRIMARY KEY (user_id, role_id)
);

CREATE INDEX user_roles_role_id_idx ON user_roles (role_id, user_id);

CREATE TABLE role_permissions (
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE stages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    sort_order SMALLINT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL REFERENCES stages(id) ON DELETE RESTRICT,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    sort_order SMALLINT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT classes_stage_code_unique UNIQUE (stage_id, code),
    CONSTRAINT classes_stage_name_unique UNIQUE (stage_id, name)
);

CREATE INDEX classes_stage_sort_idx ON classes (stage_id, sort_order, id);

CREATE TABLE subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) UNIQUE,
    name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE class_subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE RESTRICT,
    subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT class_subject_pair_unique UNIQUE (class_id, subject_id)
);

CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    staff_number VARCHAR(50) UNIQUE,
    job_title VARCHAR(100) NOT NULL,
    address VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE teaching_assignments (
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    class_subject_id BIGINT NOT NULL REFERENCES class_subjects(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (employee_id, class_subject_id)
);

CREATE INDEX teaching_assignments_subject_idx ON teaching_assignments (class_subject_id, employee_id);

CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    class_id BIGINT REFERENCES classes(id) ON DELETE RESTRICT,
    date_of_birth DATE,
    parent_phone VARCHAR(32),
    student_number VARCHAR(50) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX students_class_id_idx ON students (class_id);

CREATE TABLE lessons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_subject_id BIGINT NOT NULL REFERENCES class_subjects(id) ON DELETE RESTRICT,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    body TEXT,
    position INTEGER NOT NULL DEFAULT 1 CHECK (position > 0),
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT REFERENCES employees(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT lessons_subject_position_unique UNIQUE (class_subject_id, position)
);

CREATE TABLE learning_resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_subject_id BIGINT NOT NULL REFERENCES class_subjects(id) ON DELETE RESTRICT,
    lesson_id BIGINT REFERENCES lessons(id) ON DELETE SET NULL,
    title VARCHAR(200) NOT NULL,
    resource_type VARCHAR(20) NOT NULL CHECK (resource_type IN ('PDF', 'VIDEO', 'AUDIO', 'DOCUMENT', 'LINK')),
    description TEXT,
    storage_key TEXT,
    external_url TEXT,
    original_filename VARCHAR(255),
    mime_type VARCHAR(150),
    file_size_bytes BIGINT CHECK (file_size_bytes IS NULL OR file_size_bytes >= 0),
    source_owner VARCHAR(200),
    copyright_license VARCHAR(200),
    requires_subscription BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PENDING_REVIEW', 'APPROVED', 'REJECTED', 'ARCHIVED')),
    uploaded_by BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT learning_resources_storage_location_check CHECK (storage_key IS NOT NULL OR external_url IS NOT NULL)
);

CREATE INDEX learning_resources_catalog_idx ON learning_resources (class_subject_id, status, created_at DESC);
CREATE INDEX learning_resources_lesson_idx ON learning_resources (lesson_id) WHERE lesson_id IS NOT NULL;

CREATE TABLE resource_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT NOT NULL REFERENCES learning_resources(id) ON DELETE CASCADE,
    label VARCHAR(80) NOT NULL,
    storage_key TEXT NOT NULL,
    mime_type VARCHAR(150) NOT NULL,
    file_size_bytes BIGINT NOT NULL CHECK (file_size_bytes >= 0),
    width_px INTEGER CHECK (width_px IS NULL OR width_px > 0),
    height_px INTEGER CHECK (height_px IS NULL OR height_px > 0),
    bitrate_kbps INTEGER CHECK (bitrate_kbps IS NULL OR bitrate_kbps > 0),
    is_downloadable BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT resource_variant_label_unique UNIQUE (resource_id, label),
    CONSTRAINT resource_variant_storage_unique UNIQUE (storage_key)
);

CREATE TABLE past_exams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_subject_id BIGINT NOT NULL REFERENCES class_subjects(id) ON DELETE RESTRICT,
    title VARCHAR(150) NOT NULL,
    academic_year VARCHAR(20),
    storage_key TEXT NOT NULL,
    original_filename VARCHAR(255),
    mime_type VARCHAR(150),
    file_size_bytes BIGINT CHECK (file_size_bytes IS NULL OR file_size_bytes >= 0),
    source_owner VARCHAR(200),
    copyright_license VARCHAR(200),
    requires_subscription BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PENDING_REVIEW', 'APPROVED', 'REJECTED', 'ARCHIVED')),
    uploaded_by BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT past_exams_subject_title_year_unique UNIQUE (class_subject_id, title, academic_year)
);

CREATE INDEX past_exams_catalog_idx ON past_exams (class_subject_id, status, academic_year);

CREATE TABLE questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_subject_id BIGINT NOT NULL REFERENCES class_subjects(id) ON DELETE RESTRICT,
    lesson_id BIGINT REFERENCES lessons(id) ON DELETE SET NULL,
    question_text TEXT NOT NULL,
    question_type VARCHAR(20) NOT NULL CHECK (question_type IN ('MCQ', 'TRUE_FALSE', 'ESSAY')),
    difficulty VARCHAR(10) NOT NULL DEFAULT 'MEDIUM' CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    explanation TEXT,
    ai_generated BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PENDING_REVIEW', 'APPROVED', 'REJECTED', 'ARCHIVED')),
    created_by BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX questions_bank_idx ON questions (class_subject_id, question_type, difficulty, status);
CREATE INDEX questions_lesson_idx ON questions (lesson_id) WHERE lesson_id IS NOT NULL;

CREATE TABLE question_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    option_text TEXT NOT NULL,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order SMALLINT NOT NULL DEFAULT 0,
    CONSTRAINT question_option_order_unique UNIQUE (question_id, sort_order)
);

CREATE TABLE content_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT REFERENCES learning_resources(id) ON DELETE CASCADE,
    past_exam_id BIGINT REFERENCES past_exams(id) ON DELETE CASCADE,
    question_id BIGINT REFERENCES questions(id) ON DELETE CASCADE,
    reviewer_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    status VARCHAR(24) NOT NULL CHECK (status IN ('APPROVED', 'REJECTED', 'NEEDS_MODIFICATION')),
    feedback TEXT,
    reviewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT content_reviews_one_target CHECK (num_nonnulls(resource_id, past_exam_id, question_id) = 1)
);

CREATE INDEX content_reviews_resource_idx ON content_reviews (resource_id, reviewed_at DESC) WHERE resource_id IS NOT NULL;
CREATE INDEX content_reviews_exam_idx ON content_reviews (past_exam_id, reviewed_at DESC) WHERE past_exam_id IS NOT NULL;
CREATE INDEX content_reviews_question_idx ON content_reviews (question_id, reviewed_at DESC) WHERE question_id IS NOT NULL;

CREATE TABLE quizzes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_subject_id BIGINT NOT NULL REFERENCES class_subjects(id) ON DELETE RESTRICT,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    duration_minutes SMALLINT CHECK (duration_minutes IS NULL OR duration_minutes > 0),
    total_marks NUMERIC(8, 2) NOT NULL CHECK (total_marks > 0),
    passing_marks NUMERIC(8, 2) CHECK (passing_marks IS NULL OR (passing_marks >= 0 AND passing_marks <= total_marks)),
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    requires_subscription BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT quizzes_time_range_check CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at)
);

CREATE TABLE quiz_questions (
    quiz_id BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
    question_mark NUMERIC(8, 2) NOT NULL CHECK (question_mark > 0),
    sort_order SMALLINT NOT NULL DEFAULT 0,
    PRIMARY KEY (quiz_id, question_id),
    CONSTRAINT quiz_question_order_unique UNIQUE (quiz_id, sort_order)
);

CREATE TABLE quiz_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE RESTRICT,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
    attempt_number SMALLINT NOT NULL DEFAULT 1 CHECK (attempt_number > 0),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_at TIMESTAMPTZ,
    score NUMERIC(8, 2) CHECK (score IS NULL OR score >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS' CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'GRADED', 'CANCELLED')),
    CONSTRAINT quiz_attempt_number_unique UNIQUE (quiz_id, student_id, attempt_number),
    CONSTRAINT quiz_attempt_submission_check CHECK (submitted_at IS NULL OR submitted_at >= started_at)
);

CREATE INDEX quiz_attempts_student_idx ON quiz_attempts (student_id, started_at DESC);

CREATE TABLE student_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES quiz_attempts(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
    selected_option_id BIGINT REFERENCES question_options(id) ON DELETE RESTRICT,
    essay_answer TEXT,
    is_correct BOOLEAN,
    awarded_mark NUMERIC(8, 2) CHECK (awarded_mark IS NULL OR awarded_mark >= 0),
    answered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT student_answer_once_per_question UNIQUE (attempt_id, question_id),
    CONSTRAINT student_answer_value_check CHECK (selected_option_id IS NOT NULL OR essay_answer IS NOT NULL)
);

CREATE TABLE live_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_subject_id BIGINT NOT NULL REFERENCES class_subjects(id) ON DELETE RESTRICT,
    teacher_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    scheduled_at TIMESTAMPTZ NOT NULL,
    duration_minutes SMALLINT CHECK (duration_minutes IS NULL OR duration_minutes > 0),
    provider_code VARCHAR(80),
    provider_session_ref VARCHAR(255),
    meeting_url TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED', 'LIVE', 'COMPLETED', 'CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX live_sessions_schedule_idx ON live_sessions (scheduled_at, status);

CREATE TABLE session_recordings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES live_sessions(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    storage_key TEXT NOT NULL,
    provider_recording_ref VARCHAR(255),
    duration_seconds INTEGER CHECK (duration_seconds IS NULL OR duration_seconds >= 0),
    file_size_bytes BIGINT CHECK (file_size_bytes IS NULL OR file_size_bytes >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'PROCESSING' CHECK (status IN ('PROCESSING', 'READY', 'FAILED', 'ARCHIVED')),
    available_from TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT session_recording_storage_unique UNIQUE (storage_key)
);

CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    receiver_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    message_body TEXT NOT NULL,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT message_not_self CHECK (sender_id <> receiver_id),
    CONSTRAINT message_body_not_blank CHECK (length(btrim(message_body)) > 0)
);

CREATE INDEX messages_inbox_idx ON messages (receiver_id, sent_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX messages_outbox_idx ON messages (sender_id, sent_at DESC) WHERE deleted_at IS NULL;

CREATE TABLE subscription_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    duration_days SMALLINT NOT NULL DEFAULT 30 CHECK (duration_days > 0),
    price NUMERIC(12, 2) CHECK (price IS NULL OR price >= 0),
    currency CHAR(3),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT subscription_plan_currency_check CHECK (currency IS NULL OR currency ~ '^[A-Z]{3}$')
);

CREATE TABLE subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
    plan_id BIGINT NOT NULL REFERENCES subscription_plans(id) ON DELETE RESTRICT,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    amount_paid NUMERIC(12, 2) NOT NULL CHECK (amount_paid >= 0),
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACTIVE', 'EXPIRED', 'CANCELLED', 'REFUNDED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT subscription_period_check CHECK (ends_at > starts_at)
);

CREATE INDEX subscriptions_student_status_idx ON subscriptions (student_id, status, ends_at DESC);
CREATE INDEX subscriptions_active_lookup_idx ON subscriptions (student_id, ends_at) WHERE status = 'ACTIVE';

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES subscriptions(id) ON DELETE RESTRICT,
    provider_code VARCHAR(80) NOT NULL,
    provider_reference VARCHAR(255),
    amount NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED')),
    provider_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT payment_provider_reference_unique UNIQUE (provider_code, provider_reference)
);

CREATE INDEX payments_subscription_idx ON payments (subscription_id, created_at DESC);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action_code VARCHAR(120) NOT NULL,
    target_type VARCHAR(80),
    target_id BIGINT,
    ip_address INET,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX audit_events_actor_idx ON audit_events (actor_user_id, occurred_at DESC);
CREATE INDEX audit_events_target_idx ON audit_events (target_type, target_id, occurred_at DESC);

CREATE TABLE backup_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_key TEXT NOT NULL UNIQUE,
    checksum_sha256 CHAR(64),
    size_bytes BIGINT CHECK (size_bytes IS NULL OR size_bytes >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('CREATED', 'VERIFIED', 'FAILED', 'RESTORED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    verified_at TIMESTAMPTZ,
    notes TEXT,
    CONSTRAINT backup_checksum_format_check CHECK (checksum_sha256 IS NULL OR checksum_sha256 ~ '^[0-9a-fA-F]{64}$')
);

-- Update timestamps consistently on edited records.
CREATE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER subjects_set_updated_at BEFORE UPDATE ON subjects FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER lessons_set_updated_at BEFORE UPDATE ON lessons FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER learning_resources_set_updated_at BEFORE UPDATE ON learning_resources FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER questions_set_updated_at BEFORE UPDATE ON questions FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER live_sessions_set_updated_at BEFORE UPDATE ON live_sessions FOR EACH ROW EXECUTE FUNCTION set_updated_at();
