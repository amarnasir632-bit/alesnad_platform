ALTER TABLE students
    ADD COLUMN registration_status VARCHAR(20) NOT NULL DEFAULT 'APPROVED',
    ADD CONSTRAINT students_registration_status_valid
        CHECK (registration_status IN ('PENDING', 'NEEDS_INFO', 'APPROVED', 'REJECTED', 'SUSPENDED'));

CREATE INDEX students_registration_status_idx
    ON students (registration_status, created_at DESC);

CREATE TABLE student_admission_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    previous_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL CHECK (new_status IN ('PENDING', 'NEEDS_INFO', 'APPROVED', 'REJECTED', 'SUSPENDED')),
    reason TEXT NOT NULL DEFAULT '',
    actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX student_admission_events_history_idx
    ON student_admission_events (student_id, created_at DESC, id DESC);

CREATE TABLE student_admission_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE CHECK (token_hash ~ '^[a-f0-9]{64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    CONSTRAINT student_admission_token_expiration_valid CHECK (expires_at > created_at)
);

CREATE INDEX student_admission_tokens_active_idx
    ON student_admission_tokens (token_hash, expires_at)
    WHERE used_at IS NULL;

CREATE TABLE student_profile_correction_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    requested_changes JSONB NOT NULL CHECK (jsonb_typeof(requested_changes) = 'object'),
    reason TEXT NOT NULL CHECK (length(btrim(reason)) BETWEEN 5 AND 1000),
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    resolution_reason TEXT NOT NULL DEFAULT '',
    reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX student_profile_correction_one_pending_idx
    ON student_profile_correction_requests (user_id)
    WHERE status = 'PENDING';

CREATE INDEX student_profile_correction_queue_idx
    ON student_profile_correction_requests (status, requested_at DESC);
