CREATE TABLE IF NOT EXISTS school_schedule_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_type VARCHAR(12) NOT NULL CHECK (entry_type IN ('LESSON', 'BREAK')),
    recurrence_type VARCHAR(12) NOT NULL CHECK (recurrence_type IN ('WEEKLY', 'ONCE')),
    class_id BIGINT REFERENCES classes(id) ON DELETE CASCADE,
    class_subject_id BIGINT REFERENCES class_subjects(id) ON DELETE CASCADE,
    teacher_id BIGINT REFERENCES employees(id) ON DELETE RESTRICT,
    title VARCHAR(180) NOT NULL,
    day_of_week SMALLINT,
    occurrence_date DATE,
    starts_at TIME NOT NULL,
    ends_at TIME NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT school_schedule_time_order CHECK (ends_at > starts_at),
    CONSTRAINT school_schedule_recurrence_fields CHECK (
        (recurrence_type = 'WEEKLY' AND day_of_week IS NOT NULL AND day_of_week BETWEEN 0 AND 6 AND occurrence_date IS NULL)
        OR (recurrence_type = 'ONCE' AND day_of_week IS NULL AND occurrence_date IS NOT NULL)
    ),
    CONSTRAINT school_schedule_entry_fields CHECK (
        (entry_type = 'LESSON' AND class_id IS NOT NULL AND class_subject_id IS NOT NULL AND teacher_id IS NOT NULL AND length(btrim(title)) > 0)
        OR (entry_type = 'BREAK' AND class_subject_id IS NULL AND teacher_id IS NULL AND length(btrim(title)) > 0)
    )
);

CREATE INDEX IF NOT EXISTS school_schedule_weekly_idx
    ON school_schedule_entries (day_of_week, starts_at)
    WHERE is_active = TRUE AND recurrence_type = 'WEEKLY';

CREATE INDEX IF NOT EXISTS school_schedule_once_idx
    ON school_schedule_entries (occurrence_date, starts_at)
    WHERE is_active = TRUE AND recurrence_type = 'ONCE';

CREATE INDEX IF NOT EXISTS school_schedule_class_idx
    ON school_schedule_entries (class_id, is_active);

CREATE TABLE IF NOT EXISTS school_holidays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT REFERENCES classes(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    is_published BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT school_holiday_date_order CHECK (ends_on >= starts_on)
);

CREATE INDEX IF NOT EXISTS school_holidays_visible_idx
    ON school_holidays (starts_on, ends_on)
    WHERE is_published = TRUE;

CREATE INDEX IF NOT EXISTS school_holidays_class_idx
    ON school_holidays (class_id, ends_on);
